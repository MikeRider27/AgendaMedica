-- =====================================================================
-- Agenda Médica - esquema inicial
-- =====================================================================
-- btree_gist permite combinar igualdad (medico_id =) con solapamiento de
-- rangos (&&) en restricciones EXCLUDE: impide turnos superpuestos a nivel BD.
CREATE EXTENSION IF NOT EXISTS btree_gist;
-- unaccent: búsquedas de pacientes insensibles a tildes ("perez" encuentra "Pérez").
CREATE EXTENSION IF NOT EXISTS unaccent;

-- ---------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------
CREATE TABLE especialidades (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL,
    duracion_turno_min  INTEGER      NOT NULL DEFAULT 20 CHECK (duracion_turno_min BETWEEN 5 AND 480),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_especialidades_nombre UNIQUE (nombre)
);

CREATE TABLE aseguradoras (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL,
    activo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_aseguradoras_nombre UNIQUE (nombre)
);

CREATE TABLE consultorios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(60)  NOT NULL,
    ubicacion  VARCHAR(150),
    activo     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_consultorios_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- Pacientes
-- ---------------------------------------------------------------------
CREATE TABLE pacientes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento    VARCHAR(10)  NOT NULL DEFAULT 'CI'
                      CHECK (tipo_documento IN ('CI', 'PASAPORTE', 'RUC', 'OTRO')),
    nro_documento     VARCHAR(20)  NOT NULL,
    nombres           VARCHAR(100) NOT NULL,
    apellidos         VARCHAR(100) NOT NULL,
    fecha_nacimiento  DATE         NOT NULL,
    sexo              VARCHAR(1)   NOT NULL CHECK (sexo IN ('M', 'F', 'X')),
    telefono          VARCHAR(30),
    email             VARCHAR(150),
    direccion         VARCHAR(200),
    ciudad            VARCHAR(100),
    aseguradora_id    BIGINT       REFERENCES aseguradoras (id),
    nro_afiliado      VARCHAR(50),
    grupo_sanguineo   VARCHAR(3)   CHECK (grupo_sanguineo IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
    alergias          TEXT,
    observaciones     TEXT,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en         TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_pacientes_documento UNIQUE (tipo_documento, nro_documento)
);

CREATE INDEX ix_pacientes_apellidos ON pacientes (lower(apellidos), lower(nombres));

-- ---------------------------------------------------------------------
-- Médicos
-- ---------------------------------------------------------------------
CREATE TABLE medicos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_documento   VARCHAR(20)  NOT NULL,
    nombres         VARCHAR(100) NOT NULL,
    apellidos       VARCHAR(100) NOT NULL,
    matricula       VARCHAR(30)  NOT NULL,
    telefono        VARCHAR(30),
    email           VARCHAR(150),
    color           VARCHAR(7)   NOT NULL DEFAULT '#2563eb' CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_medicos_documento UNIQUE (nro_documento),
    CONSTRAINT uq_medicos_matricula UNIQUE (matricula)
);

CREATE TABLE medico_especialidades (
    medico_id        BIGINT NOT NULL REFERENCES medicos (id) ON DELETE CASCADE,
    especialidad_id  BIGINT NOT NULL REFERENCES especialidades (id),
    PRIMARY KEY (medico_id, especialidad_id)
);

-- Plantilla semanal de atención de cada médico.
CREATE TABLE horarios_atencion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id           BIGINT   NOT NULL,
    especialidad_id     BIGINT   NOT NULL,
    consultorio_id      BIGINT   REFERENCES consultorios (id),
    dia_semana          INTEGER  NOT NULL CHECK (dia_semana BETWEEN 1 AND 7), -- ISO: 1 = lunes
    hora_inicio         TIME     NOT NULL,
    hora_fin            TIME     NOT NULL,
    duracion_turno_min  INTEGER  NOT NULL CHECK (duracion_turno_min BETWEEN 5 AND 480),
    vigente_desde       DATE     NOT NULL DEFAULT CURRENT_DATE,
    vigente_hasta       DATE,
    activo              BOOLEAN  NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_horarios_rango CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_horarios_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
    -- el médico debe tener asignada la especialidad
    CONSTRAINT fk_horarios_medico_especialidad FOREIGN KEY (medico_id, especialidad_id)
        REFERENCES medico_especialidades (medico_id, especialidad_id) ON DELETE CASCADE
);

CREATE INDEX ix_horarios_medico_dia ON horarios_atencion (medico_id, dia_semana);

-- Ausencias, vacaciones, congresos, etc.
CREATE TABLE bloqueos_agenda (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id  BIGINT       NOT NULL REFERENCES medicos (id) ON DELETE CASCADE,
    inicio     TIMESTAMP    NOT NULL,
    fin        TIMESTAMP    NOT NULL,
    motivo     VARCHAR(200),
    CONSTRAINT ck_bloqueos_rango CHECK (fin > inicio)
);

CREATE INDEX ix_bloqueos_medico_inicio ON bloqueos_agenda (medico_id, inicio);

-- ---------------------------------------------------------------------
-- Usuarios del sistema
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(50)  NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    nombre_completo  VARCHAR(150) NOT NULL,
    email            VARCHAR(150),
    rol              VARCHAR(15)  NOT NULL CHECK (rol IN ('ADMIN', 'RECEPCION', 'MEDICO')),
    medico_id        BIGINT       REFERENCES medicos (id),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    ultimo_acceso    TIMESTAMP,
    creado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_username UNIQUE (username),
    CONSTRAINT uq_usuarios_medico UNIQUE (medico_id),
    CONSTRAINT ck_usuarios_medico CHECK (rol <> 'MEDICO' OR medico_id IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- Turnos (citas)
-- ---------------------------------------------------------------------
CREATE TABLE turnos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id         BIGINT      NOT NULL REFERENCES pacientes (id),
    medico_id           BIGINT      NOT NULL REFERENCES medicos (id),
    especialidad_id     BIGINT      NOT NULL REFERENCES especialidades (id),
    consultorio_id      BIGINT      REFERENCES consultorios (id),
    inicio              TIMESTAMP   NOT NULL,
    fin                 TIMESTAMP   NOT NULL,
    estado              VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
                        CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'EN_ATENCION', 'ATENDIDO', 'CANCELADO', 'AUSENTE')),
    tipo                VARCHAR(15) NOT NULL DEFAULT 'CONSULTA'
                        CHECK (tipo IN ('PRIMERA_VEZ', 'CONSULTA', 'CONTROL', 'PROCEDIMIENTO', 'URGENCIA')),
    motivo              VARCHAR(250),
    observaciones       TEXT,
    motivo_cancelacion  VARCHAR(250),
    creado_por          BIGINT      REFERENCES usuarios (id),
    creado_en           TIMESTAMP   NOT NULL DEFAULT now(),
    actualizado_en      TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_turnos_rango CHECK (fin > inicio),
    -- un médico no puede tener dos turnos activos superpuestos
    CONSTRAINT ex_turnos_medico_solapado EXCLUDE USING gist (
        medico_id WITH =, tsrange(inicio, fin) WITH &&
    ) WHERE (estado <> 'CANCELADO'),
    -- un paciente no puede estar en dos turnos activos a la vez
    CONSTRAINT ex_turnos_paciente_solapado EXCLUDE USING gist (
        paciente_id WITH =, tsrange(inicio, fin) WITH &&
    ) WHERE (estado <> 'CANCELADO')
);

CREATE INDEX ix_turnos_medico_inicio ON turnos (medico_id, inicio);
CREATE INDEX ix_turnos_paciente_inicio ON turnos (paciente_id, inicio);
CREATE INDEX ix_turnos_inicio ON turnos (inicio);

-- ---------------------------------------------------------------------
-- Consultas (registro de atención / historia clínica)
-- ---------------------------------------------------------------------
CREATE TABLE consultas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id          BIGINT       REFERENCES turnos (id),
    paciente_id       BIGINT       NOT NULL REFERENCES pacientes (id),
    medico_id         BIGINT       NOT NULL REFERENCES medicos (id),
    especialidad_id   BIGINT       NOT NULL REFERENCES especialidades (id),
    fecha             TIMESTAMP    NOT NULL DEFAULT now(),
    motivo_consulta   TEXT         NOT NULL,
    anamnesis         TEXT,
    examen_fisico     TEXT,
    diagnostico       TEXT,
    indicaciones      TEXT,
    peso_kg           NUMERIC(5,2) CHECK (peso_kg > 0),
    talla_cm          NUMERIC(5,1) CHECK (talla_cm > 0),
    presion_arterial  VARCHAR(10),
    temperatura_c     NUMERIC(4,1),
    proximo_control   DATE,
    creado_en         TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_consultas_turno UNIQUE (turno_id)
);

CREATE INDEX ix_consultas_paciente_fecha ON consultas (paciente_id, fecha DESC);
